-- Local-only fixture for testing migration 045 on a throwaway Postgres. NEVER apply to the linked project.
--
-- Just enough of the live schema for the insert path: roles, spatial_hazards (every column the live table
-- has, so v3's INSERT column list is valid), hazard_audit_log and trigger_hazard_audit exactly as 000+022
-- define them, security_events as 024+027 define it (with 027's ping trigger over a stub of net.http_post
-- that records each call, and 027's claim_security_pushes), and a STUB upsert_spatial_hazard_v3 with the
-- live signature that runs the same INSERT statement as the live function's insert branch (041), minus merge
-- and member bookkeeping.
--
-- Omitted on purpose: trg_spatial_hazard_expiry (037, BEFORE INSERT; needs the lifetime tables) and
-- trg_hazard_confirm_member (031, AFTER UPDATE). Neither touches hazard_audit_log or security_events and
-- neither is an AFTER INSERT trigger, so neither can change the order or result of what 045 adds.
--
-- Owner. The harness runs this twice: once with the objects owned by warn_owner, a NON-superuser standing in
-- for Supabase's postgres role (tables with RLS enabled are readable/writable by their owner only, exactly as
-- on the live project, so a SECURITY DEFINER function owned by anyone else would see nothing), and once with
-- everything owned by the cluster superuser. The two `-- OWNER` lines are what the harness toggles.

create role warn_owner nosuperuser nocreatedb nocreaterole noinherit;
create role anon nologin;
create role authenticated nologin;
create role service_role nologin;
grant usage on schema public to warn_owner, anon, authenticated, service_role;
grant create on schema public to warn_owner;

-- 027 puts pg_net's http_post in schema net and lists 'extensions' on the ping function's search_path.
create schema extensions;
create schema net;
create table net.http_post_calls (id bigserial primary key, called_at timestamptz default now(), url text, body jsonb);
create function net.http_post(url text, body jsonb default '{}'::jsonb, headers jsonb default '{}'::jsonb)
returns bigint language plpgsql as $$
declare v_id bigint;
begin
    insert into net.http_post_calls as c (url, body) values ($1, $2) returning c.id into v_id;
    return v_id;
end;
$$;
grant usage on schema net, extensions to warn_owner;
grant select, insert on net.http_post_calls to warn_owner;
grant usage, select on sequence net.http_post_calls_id_seq to warn_owner;

set role warn_owner; -- OWNER

