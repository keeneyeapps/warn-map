-- 027's push decision, verbatim: what the Edge Function calls when pinged.
create function public.claim_security_pushes()
returns table(kind text)
language plpgsql security definer set search_path to 'public', 'pg_temp' as $$
declare r record;
begin
  perform pg_advisory_xact_lock(hashtext('warn.security_push'));
  for r in select distinct e.kind from security_events e where e.push_state is null loop
    if exists (select 1 from security_events e
                where e.kind = r.kind and e.push_state = 'pushed' and e.push_at > now() - interval '1 hour') then
      update security_events set push_state = 'suppressed', push_at = now()
       where security_events.kind = r.kind and push_state is null;
    else
      update security_events set push_state = 'pushing', push_at = now()
       where security_events.kind = r.kind and push_state is null;
      kind := r.kind;
      return next;
    end if;
  end loop;
end;
$$;
revoke all on function public.claim_security_pushes() from public, anon, authenticated;
grant execute on function public.claim_security_pushes() to service_role;

create function public.ping_security_notify() returns trigger
language plpgsql security definer set search_path = public, extensions, pg_temp as $$
begin
    begin
        perform net.http_post(
            url := 'https://example.invalid/functions/v1/security-notify',
            body := '{}'::jsonb, headers := '{"Content-Type": "application/json"}'::jsonb);
    exception when others then
        raise warning 'ping_security_notify: could not queue the notify request: %', sqlerrm;
    end;
    return new;
end;
$$;
revoke all on function public.ping_security_notify() from public, anon, authenticated;
create trigger security_events_ping_notify after insert on public.security_events
    for each row execute function public.ping_security_notify();

-- STUB of upsert_spatial_hazard_v3: live signature (028/041), live INSERT column list and created_at clamp
-- (019), SECURITY DEFINER, callable by anon. No merge, no hazard_members, no provenance validation.
create function public.upsert_spatial_hazard_v3(
    p_region_code text, p_category text, p_hazard_type text,
    p_latitude double precision, p_longitude double precision,
    p_heading double precision default null,
    p_created_at timestamptz default now(),
    p_specific text default null, p_display_text text default null,
    p_road_way_id bigint default null, p_retract_token text default null,
    p_position_accuracy_m double precision default null,
    p_position_fix_age_ms bigint default null,
    p_heading_sigma_deg double precision default null,
    p_heading_source text default null,
    p_provider_heading_deg double precision default null,
    p_provider_heading_sigma_deg double precision default null,
    p_provider_heading_source text default null)
returns table(hazard_id bigint, was_inserted boolean, provenance_dropped text)
language plpgsql security definer set search_path = public, pg_temp as $$
declare v_new_id bigint;
begin
    insert into spatial_hazards (
        region_code, category, hazard_type, latitude, longitude, heading, created_at,
        specific, display_text, road_way_id, retract_token_hash,
        position_accuracy_m, position_fix_age_ms, heading_sigma_deg, heading_source,
        provider_heading_deg, provider_heading_sigma_deg, provider_heading_source)
    values (
        p_region_code, p_category, p_hazard_type, p_latitude, p_longitude, p_heading,
        least(p_created_at, now() + interval '1 hour'),
        p_specific, p_display_text, p_road_way_id,
        case when p_retract_token is null then null else encode(sha256(p_retract_token::bytea), 'hex') end,
        p_position_accuracy_m, p_position_fix_age_ms::integer, p_heading_sigma_deg, p_heading_source,
        p_provider_heading_deg, p_provider_heading_sigma_deg, p_provider_heading_source)
    returning id into v_new_id;
    return query select v_new_id, true, null::text;
end;
$$;
grant execute on function public.upsert_spatial_hazard_v3(text, text, text, double precision, double precision,
    double precision, timestamptz, text, text, bigint, text, double precision, bigint, double precision, text,
    double precision, double precision, text) to anon;

